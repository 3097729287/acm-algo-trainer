const evidence=new Map(Array.from({length:5},(_,id)=>[id,{id,weight:1,score:80,solved:true,rated:true}]));
assert.equal(combineKnowledgeEvidence([0,1,2,3,0,1],evidence).value,null,'duplicate topic membership cannot inflate a four-question sample');
assert.equal(combineKnowledgeEvidence([0,1,2,3,4,0,1],evidence).value,54,'small samples receive a quantity discount');
assert.equal(combineKnowledgeEvidence([0,1,2,3,4],evidence,{},[{name:'first',ids:[0,1,2,3,4]},{name:'missing',ids:[]}]).value,null,'each child needs evidence');
assert.equal(combineKnowledgeEvidence([0,1,2,3,4],evidence,{},[{name:'first',ids:[0,1,2,3,4]},{name:'same questions',ids:[0,1,2,3,4]}]).value,null,'five multi-tagged questions cannot qualify an entire parent');
assert.equal(combineKnowledgeEvidence([0,1,2,3,4],new Map([...evidence].map(([id,item])=>[id,{...item,rated:false}]))).value,null);
