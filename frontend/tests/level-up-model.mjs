import assert from 'node:assert/strict';
import {PAGE_UNLOCKS,availablePages,canOpenPage,newlyUnlocked,nextUnlock} from '../src/lib/featureUnlocks.js';
import {acceptGrowth,observeLevel,acknowledgeLevel,mergeLevelNotices,protectGrowth} from '../src/lib/levelNotices.js';
const owner='fixture-owner',growth=(level,revision,epoch='first')=>({level,confirmed:true,authority:{owner,epoch,revision}});
assert.deepEqual(availablePages(1),['mine','training-lists','records','settings']);
assert(canOpenPage('rankings',2));assert(!canOpenPage('paths',3));assert(canOpenPage('paths',4));
assert.deepEqual(newlyUnlocked(1,4).map(item=>item.id),['library','rankings','competitions','mock','paths','templates','lectures']);
assert.equal(nextUnlock(5).length,0);assert.equal(new Set(PAGE_UNLOCKS.map(item=>item.id)).size,PAGE_UNLOCKS.length);
const old=observeLevel({},11);assert.deepEqual(old,{levelNoticeVersion:1,levelNoticeSeen:11,levelNoticePending:0});
const initial=observeLevel({},1),queued=observeLevel(initial,4);assert.equal(queued.levelNoticePending,4);
const more=observeLevel(queued,5);assert.equal(more.levelNoticePending,5);
const acknowledged=acknowledgeLevel(more,4);assert.equal(acknowledged.levelNoticeSeen,4);assert.equal(acknowledged.levelNoticePending,5);
assert.equal(acknowledgeLevel(acknowledged,5).levelNoticePending,0);
assert.equal(mergeLevelNotices(more,{levelNoticeVersion:1,levelNoticeSeen:5,levelNoticePending:0}).levelNoticePending,0);
let stamp=acceptGrowth(null,growth(3,4),owner);assert(stamp);
assert.equal(acceptGrowth(stamp,growth(2,2),owner),null);assert.equal(acceptGrowth(stamp,growth(3,4),owner),null);
assert.equal(acceptGrowth(stamp,{...growth(4,5),authority:{owner:'other',epoch:'first',revision:5}},owner),null);
stamp=acceptGrowth(stamp,growth(4,1,'restart'),owner);assert.equal(acceptGrowth(stamp,growth(3,9,'first'),owner),null);
const recent={growth:growth(4,9)},stale={growth:growth(2,2)};
assert.equal(protectGrowth(recent,stale,owner).growth.level,4);
assert.equal(protectGrowth(recent,{growth:{level:99}},owner).growth.level,4);
console.log('PASS exact feature configuration, old-account baseline, pending merge/restart state, rendered-only acknowledgement, stale-owner/revision/epoch rejection');
