import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {createServer} from 'vite';
import {chromium} from 'playwright';
const vite=await createServer({cacheDir:'../.backups/leaderboard-reconnect-20261108/vite',optimizeDeps:{entries:['tests/rankings-fixture.html']},server:{host:'127.0.0.1',port:24987,strictPort:true,watch:null}});
await vite.listen();
const browser=await chromium.launch({channel:process.env.CI?undefined:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));page.setDefaultTimeout(10000);
const output='../.backups/leaderboard-reconnect-20261108';await mkdir(output,{recursive:true});
try{
 await page.goto(vite.resolvedUrls.local[0]+'tests/rankings-fixture.html?disconnected=1');
 await page.getByRole('heading',{name:'排行榜暂时无法连接',exact:true}).waitFor();
 assert.equal(await page.getByText('暂无过题记录',{exact:true}).count(),0);
 assert((await page.locator('.ranking-board-summary').innerText()).includes('—'));
 await page.screenshot({path:output+'/initial-connection-pending.png'});
 await page.evaluate(()=>window.rankingState=null);
 await page.getByRole('button',{name:'重试连接',exact:true}).click();
 await page.locator('.ranking-table tbody tr').first().waitFor();
 assert.equal(await page.evaluate(()=>window.rankingReconnects),1,'Retry reconnects the authenticated account before restarting rankings');
 assert.equal(await page.locator('.ranking-table tbody tr').count(),4);
 await page.evaluate(()=>window.rankingState={status:'unconfigured',hasSnapshot:false,entries:[],self:null});
 await page.getByRole('button',{name:'同步与刷新',exact:true}).click();
 await page.getByRole('status').filter({hasText:'部分数据刷新未完成'}).waitFor();
 assert.equal(await page.locator('.ranking-table tbody tr').count(),4,'A disconnected refresh retains the verified board');
 assert.equal(await page.getByText('暂无过题记录',{exact:true}).count(),0);
 await page.screenshot({path:output+'/verified-board-kept-during-outage.png'});
 await page.getByRole('tab',{name:'本周',exact:true}).click();
 await page.getByRole('heading',{name:'排行榜暂时无法连接',exact:true}).waitFor();
 assert.equal(await page.locator('.ranking-table tbody tr').count(),0,'Daily scores never appear as a weekly snapshot');
 await page.getByRole('tab',{name:'每日',exact:true}).click();
 await page.locator('.ranking-table tbody tr').first().waitFor();
 await page.evaluate(()=>window.rankingState=null);
 await page.getByRole('status').filter({hasText:'部分数据刷新未完成'}).waitFor({state:'hidden'});
 assert.equal(await page.locator('.ranking-table tbody tr').count(),4);
 assert.deepEqual(errors,[]);
 const result={ok:true,firstConnectionIsNotAnEmptyBoard:true,accountReconnectOnRetry:true,verifiedBoardSurvivesOutage:true,periodIsolation:true,automaticRecovery:true,errors};
 await writeFile(output+'/ui-result.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}catch(error){await page.screenshot({path:output+'/failure.png'});throw error;}finally{await browser.close();await vite.close();}
