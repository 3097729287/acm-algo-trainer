import assert from 'node:assert/strict';
import {availablePages,pageAvailable,hiddenPages} from '../src/lib/navigationVisibility.js';
import {nextActions} from '../src/lib/nextActions.js';
assert.deepEqual(availablePages(1),['mine','training-lists','records','settings']);
assert(!pageAvailable('mock',2));assert(pageAvailable('mock',3));
assert(pageAvailable('growth',5));assert(pageAvailable('rankings',2));
assert.deepEqual(hiddenPages(['mine','records','settings','library','library','bad']),['library']);
assert(!pageAvailable('training-lists',11,{hiddenNavPages:['training-lists']}));
const row=(id,difficulty=1000,extra={})=>({id,title:id,difficulty,tags:['数组','排序'],catalogContentReady:true,...extra});
const rows=[row('done',1000,{accepted:true}),row('next'),row('stretch',1400,{difficultyConfidence:'HIGH'}),row('missing',900,{catalogContentReady:false}),row('template',null,{catalogHidden:true})];
const base={rows,training:[],availablePages:availablePages(11),prefs:{},insights:{assessment:{recommendationLevel:1200},growth:{ranked:{evidenceCount:6,recentPerformance:{attempted:8,firstPass:6,independentSolved:6}}}},templates:[{id:'builtin:sort',builtin:true,title:'排序模板',tags:['排序'],practiceIds:['template']} ]};
const result=nextActions(base);
assert(result.some(item=>item.kind==='course'&&item.id==='sorting-basics'));
assert(result.some(item=>item.kind==='template'&&item.id==='builtin:sort'));
assert(result.some(item=>item.kind==='template-problem'&&item.id==='template'));
assert(result.some(item=>item.kind==='stretch'&&item.id==='stretch'));
assert(!result.some(item=>item.id==='missing'||item.id==='done'));
assert(result.every(item=>item.reason.length>20));
const hidden=nextActions({...base,availablePages:availablePages(11,{hiddenNavPages:['paths','templates','library']})});
assert(!hidden.some(item=>['course','template','template-problem','stretch'].includes(item.kind)));
const pending=nextActions({...base,training:[row('due',1200,{queue:'review',reviewDueAt:'2026-10-28'})]});
assert.equal(pending[0].id,'due');
assert(!nextActions({...base,insights:{assessment:{recommendationLevel:1200}}}).some(item=>item.kind==='stretch'));
assert.deepEqual(nextActions({...base,activeContest:{id:'contest',name:'已有试卷'}}).map(item=>item.kind),['contest']);
console.log('PASS navigation levels, protected pages, hidden dependency actions, evidence-backed next steps, real content readiness and active-contest priority');
