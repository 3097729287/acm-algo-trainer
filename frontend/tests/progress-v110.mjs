// Public fixture only: no personal databases, external network, or official submissions.
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
const server=await createServer({server:{host:'127.0.0.1',port:0}});
await server.listen();
const browser=await chromium.launch({channel:process.env.CI?undefined:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1100}});
page.setDefaultTimeout(15000);
const errors=[];
page.on('pageerror',issue=>errors.push(issue.message));
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/progress-v110-fixture.html`);
  await page.locator('.growth-profile-identity').getByText('成长测试用户',{exact:true}).waitFor();
  assert.match(await page.locator('.growth-profile-identity').textContent(),/TB-PUBLICFIXTUREID/);
  assert.deepEqual(await page.locator('.progress-platform-scores > div > span:first-child').allTextContents(),['Codeforces','AtCoder']);
  assert.equal(await page.locator('.growth-title-showcase .title-medal').count(),1);
  assert.equal(await page.getByLabel('题面翻译配置',{exact:true}).count(),0,'translation stays unmounted until expanded');
  assert.equal(await page.getByLabel('公开账号连接',{exact:true}).count(),0,'public account editor stays unmounted until expanded');
  assert.equal(await page.evaluate(()=>window.fixtureRequests.filter(x=>x.path==='translation/settings').length),0);
  await page.getByText('公开账号与评分',{exact:true}).click();
  await page.getByRole('textbox',{name:'Codeforces公开账号',exact:true}).waitFor();
  await page.getByText('翻译 API',{exact:true}).click();
  await page.getByLabel('翻译模型',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>window.fixtureRequests.filter(x=>x.path==='translation/settings').length),1);
  await page.locator('.progress-recommendation').click();
  assert.deepEqual(await page.evaluate(()=>window.fixtureActions.at(-1)),{kind:'train',id:'fixture-0'});
  assert.equal(await page.locator('.progress-recommendation button').count(),0);
  await page.getByRole('button',{name:'比赛测试',exact:true}).click();
  await page.locator('.competition-card').first().waitFor();
  assert.equal(await page.locator('.competition-card').count(),40,'only one page is mounted');
  await page.getByRole('button',{name:'开始比赛 ABC 1',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>window.fixtureActions.at(-1)),{kind:'start',name:'ABC 1'});
  assert.equal(await page.getByLabel('比赛列表',{exact:true}).count(),1,'start does not require opening details');
  await page.getByRole('button',{name:'下一页',exact:true}).click();
  assert.match(await page.locator('.competition-card-title').first().textContent(),/ABC 41/);
  await page.getByLabel('搜索比赛',{exact:true}).fill('ABC 85');
  await page.waitForFunction(()=>document.querySelectorAll('.competition-card').length===1);
  await page.getByRole('button',{name:'查看 AtCoder ABC 85，1 道题',exact:true}).click();
  await page.getByRole('button',{name:'练习 A 题目 84',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>window.fixtureActions.at(-1)),{kind:'train',id:'fixture-84'});
  assert.equal(await page.locator('.competition-question button').count(),0);
  await page.getByRole('button',{name:'成就测试',exact:true}).click();
  assert.equal(await page.locator('.progress-achievement-new').count(),2);
  const first=page.locator('[data-achievement-id="official-500"]');
  assert.match(await first.textContent(),/解题能手 · 称号已获得/);
  assert.doesNotMatch(await first.textContent(),/XP/);
  await first.hover();
  assert.equal(await page.locator('.progress-achievement-new').count(),1,'hover dismisses only the viewed new achievement');
  await page.locator('[data-achievement-id="streak-30"]').focus();
  assert.equal(await page.locator('.progress-achievement-new').count(),0,'keyboard focus also marks an achievement seen');
  await page.getByRole('button',{name:'成长测试',exact:true}).click();
  await page.getByRole('button',{name:'成就测试',exact:true}).click();
  assert.equal(await page.locator('.progress-achievement-new').count(),0,'seen state remains dismissed on reopen');
  await mkdir('tests/screenshots/progress-v110',{recursive:true});
  await page.screenshot({path:'tests/screenshots/progress-v110/achievements.png'});
  await page.getByRole('button',{name:'成长测试',exact:true}).click();
  await page.screenshot({path:'tests/screenshots/progress-v110/growth.png',fullPage:true});
  await page.setViewportSize({width:850,height:1000});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await page.getByRole('button',{name:'比赛测试',exact:true}).click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,paginatedContests:40,directReproduction:true,wholeRowPractice:true,lazyAccountPanels:true,publicPlatformScoresOnly:true,titleRewards:true,newAchievementHoverAndFocus:true,realSubmissions:false}));
} finally {await browser.close();await server.close();}
