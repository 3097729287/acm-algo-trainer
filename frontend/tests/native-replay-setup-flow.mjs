import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {nativeRead as rpc,normalDrafts} from './native-contest-setup-flow.mjs';
import {openMockSelection} from './mock-mode-selection.mjs';

export async function exerciseNativeReplaySetup(page,output){
 const name='CCPC 2026 长春区域赛',ordinary=await normalDrafts(page);
 const trainingBefore=new Set((await rpc(page,'workspace')).training.map(row=>row.id));
 assert.equal((await rpc(page,'workspace')).activeContest,null);
 const home=page.getByRole('button',{name:'返回主界面',exact:true}).first();
 if(await home.isVisible()){await home.click();await home.waitFor({state:'hidden'});}
 await page.setViewportSize({width:1500,height:950});await page.keyboard.press('Control+5');
 const setup=page.locator('.mock-create');await setup.waitFor();
 await page.getByRole('button',{name:'训练筛选',exact:true}).click();
 const filter=page.getByRole('dialog',{name:'训练筛选',exact:true});
 await filter.getByRole('button',{name:'全部比赛',exact:true}).click();
 await filter.getByRole('button',{name:'关闭筛选',exact:true}).click();
 const menu=await openMockSelection(page,'重现赛');
 await page.waitForFunction(name=>[...document.querySelectorAll('select[aria-label="重现赛比赛"] option')].some(option=>option.value===name),name);
 for(const folder of ['XCPC','CCPC 区域赛','2026年'])await menu.getByRole('option',{name:folder,exact:true}).click();
 const option=menu.locator(`button[data-value="${name}"]`);await option.waitFor();
 assert.equal(await option.isDisabled(),false);assert.match(await option.innerText(),/13 题.*题面待核验/);
 await page.screenshot({path:resolve(output,'native-partial-replay-selectable.png')});
 await option.click();await menu.waitFor({state:'detached'});
 await setup.getByRole('button',{name:'生成试卷',exact:true}).click();
 const preview=setup.locator('.paper-preview');await preview.waitFor();
 assert.equal(await preview.locator('.paper-slot').count(),13);
 assert.equal(await preview.locator('.paper-slot small').count(),1);
 assert.match(await preview.locator('.paper-slot').nth(8).innerText(),/I.*题面缺失/s);
 await preview.getByRole('button',{name:'重命名模拟赛',exact:true}).click();
 const title=preview.getByRole('textbox',{name:'模拟赛名称',exact:true});await title.fill('原生部分赛实际重现');await title.press('Enter');
 await setup.getByRole('button',{name:'开始训练',exact:true}).click();
 let workbench=page.locator('.contest-player .tb-workbench:visible');await workbench.waitFor();
 const active=(await rpc(page,'workspace')).activeContest;
 assert.equal(active.total,13);assert.equal(active.constraints.strategy,'replay');
 assert.equal(active.slots[8].letter,'I');assert.equal(active.slots[8].statementAvailable,false);
 assert(!active.constraints.backgroundReward);assert.equal(active.accepted,0);
 assert.deepEqual(await normalDrafts(page),ordinary);
 for(const row of active.slots)assert.equal((await rpc(page,'workspace')).training.some(item=>item.id===row.id),trainingBefore.has(row.id));
 let editor=workbench.locator('.cm-content[contenteditable=true]:visible').first();
 if(!await editor.isVisible())await page.keyboard.press('Alt+2');await editor.waitFor();await editor.click();await editor.press('Alt+0');
 await page.getByRole('button',{name:'选择比赛题目，当前 A',exact:true}).click();
 const picker=page.getByRole('menu',{name:'模拟赛题目',exact:true});
 assert.equal(await picker.getByRole('menuitemradio').count(),13);assert(await picker.getByRole('menuitemradio').nth(8).isDisabled());
 await page.screenshot({path:resolve(output,'native-partial-replay-missing-picker.png')});
 await picker.getByRole('menuitemradio').nth(7).click();
 workbench=page.locator(`.tb-workbench[data-problem-id="${active.slots[7].id}"]:visible`);await workbench.waitFor();
 await workbench.getByRole('button',{name:'下一题',exact:true}).click();
 workbench=page.locator(`.tb-workbench[data-problem-id="${active.slots[9].id}"]:visible`);await workbench.waitFor();
 await page.getByRole('button',{name:'选择比赛题目，当前 J',exact:true}).waitFor();
 editor=workbench.locator('.cm-content[contenteditable=true]:visible').first();
 if(!await editor.isVisible())await page.keyboard.press('Alt+2');await editor.waitFor();
 const code='// native original replay journal; real isolated draft 😀\nint main(){return 0;}\n';
 await editor.fill(code);await editor.press('Control+s');
 await page.waitForFunction(async({id,contestId,code})=>{
  const result=await window.__TAURI__.core.invoke('api_request',{request:{version:1,id:crypto.randomUUID(),method:'GET',path:'problem',query:{id:[id],contestId:[contestId]}}});
  return result.ok&&result.data.draft===code;
 },{id:active.slots[9].id,contestId:active.id,code});
 await page.screenshot({path:resolve(output,'native-partial-replay-skips-to-j.png')});
 await page.getByRole('button',{name:'结束比赛',exact:true}).click();
 await page.getByRole('alertdialog',{name:'结束比赛确认',exact:true}).getByRole('button',{name:'结束并复盘',exact:true}).click();
 const details=page.locator('.record-detail');await details.getByRole('heading',{name:'原生部分赛实际重现',exact:true}).waitFor();
 assert.equal(await details.locator('.record-slot').count(),13);assert.match(await details.innerText(),/0\/13 AC/);
 assert.deepEqual(await normalDrafts(page),ordinary);
 const after=new Set((await rpc(page,'workspace')).training.map(row=>row.id));
 for(const row of active.slots)assert.equal(after.has(row.id),row.id===active.slots[9].id||trainingBefore.has(row.id));
 await page.screenshot({path:resolve(output,'native-partial-replay-finished.png')});
 return {realTauriIpc:true,contestsInsertedByFixtureForThisFlow:0,originalPublicContest:name,originalSlots:13,availableSlots:12,missingLetter:'I',actualPartialMenuSelection:true,actualReactPreviewAndStart:true,originalLetterOrderPreserved:true,missingMenuItemDisabled:true,nextSkipsHToJ:true,actualDraftSavedAndScoped:true,untouchedSlotsNotEnrolled:true,ordinaryDraftRowsUnchanged:true,actualFinishAndReview:true,officialAcClaims:0,backgroundRewardPolicyCreated:false,externalSubmissionsSent:0};
}
