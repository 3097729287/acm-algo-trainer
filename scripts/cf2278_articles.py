def inline(text):
    chunks=re.split(r'(```[^\n]*\n.*?^```)',text,flags=re.S|re.M)
    def prose(chunk):
        chunk=re.sub(r'<code>(.*?)</code>',lambda m:'$\\verb@'+html.unescape(m[1])+'@$',chunk)
        return re.sub(r'`([^`\n]+)`',lambda m:'$\\verb@'+m[1]+'@$',chunk)
    return ''.join(chunk if i%2 else prose(chunk) for i,chunk in enumerate(chunks))

