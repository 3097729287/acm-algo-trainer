def write(path,text):
    # This archive uses KaTeX verbatim spans for inline C++ syntax; unlike
    # unprotected HTML code spans they survive the legacy math normalizer.
    chunks=re.split(r'(```[^\n]*\n.*?^```)',text,flags=re.M|re.S)
    text=''.join(chunk if i%2 else re.sub(r'`([^`\n]+)`',lambda m:'$\\verb@'+m[1]+'@$',chunk) for i,chunk in enumerate(chunks))
    path.parent.mkdir(parents=True,exist_ok=True)
    if path.exists() and path.read_text('utf8')!=text:
        saved=Path.home()/'.dsh/backups/three-contests-20261102'/dt.datetime.now().strftime('%Y%m%d-%H%M%S-%f')/path.parent.name/path.name
        saved.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(path,saved)
    path.write_text(text,encoding='utf8',newline='\n')

def foundations(key,letter):
    lectures={r['id']:r['content'] for r in read(ROOT/'data/library/lectures.json')}
    result=[]
    for name in META[key,letter][3]:
        v=lectures['lecture:foundation-'+name]
        body=v['markdown'];body=re.sub(r'(?m)^#{1,3} (.*)$',r'#### \1',body)
        body=body.replace('```cpp','```cxx')
        for rel in re.findall(r'!\[[^\]]*\]\(([^)]+)\)',body):
            uri=v['images'][rel]
            suffix=Path(rel).suffix
            target=f'assets/foundation-{name}-{Path(rel).name}'
            payload=base64.b64decode(uri.split(',',1)[1])
            platform,series,number,_,_=ROUNDS[key]
            for folder in [CONTENT/key,ARCHIVE/platform/series/number]:
                p=folder/target;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(payload)
            body=body.replace(']('+rel+')',']('+target+')')
        title=v.get('displayTitle') or v['title'].removeprefix('从零讲：')
        result.append(f'### 从零讲：{title}\n\n<details>\n<summary>展开可复用的基础知识</summary>\n\n{body}\n\n</details>')
    return '\n\n'.join(result)

