def translate(original, letter):
    pieces = re.split(r'(\n\n+)', original)
    blocks = pieces[::2]
    assert len(blocks) == len(TEXT[letter]), (letter, len(blocks), len(TEXT[letter]))
    result = []
    for i, (source, template) in enumerate(zip(blocks, TEXT[letter])):
        if template is None:
            result.append(source)
            continue
        spans = PROTECTED.findall(source)
        used = [int(x) for x in re.findall(r'@(\d+)', template)]
        assert sorted(used) == list(range(len(spans))), (letter, i, used, spans)
        result.append(re.sub(r'@(\d+)', lambda m: spans[int(m[1])], template))
    for index, translated in enumerate(result):
        pieces[2*index] = translated
    return ''.join(pieces)

def main():
    statements = json.loads((CONTENT/'statements.json').read_text('utf8'))
    for row in statements:
        value = row['content']; letter = row['problem_id'].rsplit('::',1)[1]
        original = value['markdown']; chinese = translate(original, letter)
        value['translation'] = {'kind':'bundled', 'provider':'ToBe 中文题面复核',
            'format':TRANSLATION_FORMAT, 'sourceHash':hashlib.sha256(original.encode()).hexdigest(),
            'sourceLanguage':'en', 'targetLanguage':'zh-CN', 'markdown':chinese,
            'notice':'中文译文；公式、数值、输入输出与样例保留原题。C 题的终止条件歧义在题解中注明。' if letter=='C' else '中文译文；公式、数值、输入输出与样例保留原题。'}
        assert bundled_translation(value), letter
        put(CONTENT/'statements'/(letter+'.json'), json.dumps(value,ensure_ascii=False,indent=2,sort_keys=True)+'\n')
    put(CONTENT/'statements.json', json.dumps(statements,ensure_ascii=False,indent=2,sort_keys=True)+'\n')
    print('Six Chinese statements passed complete-prose and immutable-span validation.')

if __name__=='__main__': main()
